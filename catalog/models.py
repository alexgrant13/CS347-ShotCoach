from django.conf import settings
from django.core.validators import MaxValueValidator, MinValueValidator
from django.db import models
from django.urls import reverse


class Profile(models.Model):
    """Extra info about a user. Gear and skill level personalize coaching tips."""

    class SkillLevel(models.TextChoices):
        BEGINNER = "beginner", "Beginner"
        INTERMEDIATE = "intermediate", "Intermediate"
        ADVANCED = "advanced", "Advanced"

    user = models.OneToOneField(
        settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="profile"
    )
    skill_level = models.CharField(
        max_length=20, choices=SkillLevel.choices, default=SkillLevel.BEGINNER
    )
    camera = models.CharField(
        max_length=100, blank=True, help_text="e.g. iPhone 15 Pro, Canon R50"
    )
    lenses = models.CharField(
        max_length=200, blank=True, help_text="e.g. 24mm main, 50mm f/1.8"
    )
    favorite_styles = models.CharField(
        max_length=200, blank=True, help_text="e.g. Portrait, Street, Night"
    )

    def __str__(self):
        return f"{self.user.username}'s profile"


class Reference(models.Model):
    """A professional photo pulled from the Pexels API."""

    pexels_id = models.PositiveIntegerField(unique=True)
    image_url = models.URLField(max_length=500, help_text="Direct link to the image file")
    page_url = models.URLField(max_length=500, help_text="Photo's page on Pexels")
    photographer = models.CharField(max_length=100)
    photographer_url = models.URLField(max_length=500, blank=True)
    alt_text = models.CharField(max_length=300, blank=True)

    class Meta:
        ordering = ["-id"]

    def __str__(self):
        return f"Pexels #{self.pexels_id} by {self.photographer}"


class Shot(models.Model):
    """A photo the user uploaded, plus what ShotCoach learned about it."""

    owner = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="shots"
    )
    image = models.ImageField(upload_to="shots/%Y/%m/")
    title = models.CharField(max_length=100)
    idea_text = models.TextField(
        blank=True, help_text="What the user was going for (optional)"
    )
    keywords = models.JSONField(
        default=list, blank=True, help_text="Search keywords generated by the AI"
    )

    # Camera settings read from the photo's EXIF data (may be missing)
    aperture = models.DecimalField(
        max_digits=4, decimal_places=1, null=True, blank=True, help_text="f-number, e.g. 2.8"
    )
    shutter_speed = models.CharField(
        max_length=20, blank=True, help_text='e.g. "1/250"'
    )
    iso = models.PositiveIntegerField(null=True, blank=True)
    focal_length = models.PositiveIntegerField(
        null=True, blank=True, help_text="In millimeters"
    )

    references = models.ManyToManyField(
        Reference, through="ShotMatch", related_name="matched_shots", blank=True
    )
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]

    def __str__(self):
        return self.title

    def get_absolute_url(self):
        return reverse("shot-detail", args=[str(self.id)])

    def settings_summary(self):
        parts = []
        if self.aperture:
            parts.append(f"f/{self.aperture}")
        if self.shutter_speed:
            parts.append(f"{self.shutter_speed}s")
        if self.iso:
            parts.append(f"ISO {self.iso}")
        if self.focal_length:
            parts.append(f"{self.focal_length}mm")
        return " · ".join(parts) or "No EXIF data"

    settings_summary.short_description = "Camera settings"


class ShotMatch(models.Model):
    """Links a Shot to a similar Reference, with how similar they are."""

    shot = models.ForeignKey(Shot, on_delete=models.CASCADE, related_name="matches")
    reference = models.ForeignKey(Reference, on_delete=models.CASCADE)
    similarity = models.FloatField(
        validators=[MinValueValidator(0.0), MaxValueValidator(1.0)],
        help_text="0 to 1, higher is more similar",
    )
    rank = models.PositiveSmallIntegerField(help_text="1 = best match")

    class Meta:
        ordering = ["shot", "rank"]
        verbose_name_plural = "shot matches"
        constraints = [
            models.UniqueConstraint(fields=["shot", "reference"], name="unique_shot_reference")
        ]

    def __str__(self):
        return f"{self.shot} → {self.reference} ({self.similarity:.0%})"


class Critique(models.Model):
    """AI coaching tips for a Shot. A shot can be re-coached, so it may have several."""

    shot = models.ForeignKey(Shot, on_delete=models.CASCADE, related_name="critiques")
    tips = models.TextField()
    model_name = models.CharField(
        max_length=100, blank=True, help_text="Which LLM wrote the tips"
    )
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]

    def __str__(self):
        return f"Critique of {self.shot} ({self.created_at:%b %d, %Y})"


class Board(models.Model):
    """A collection of saved references, usually for a planned shoot."""

    owner = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="boards"
    )
    name = models.CharField(max_length=100)
    description = models.TextField(blank=True)
    shoot_date = models.DateField(null=True, blank=True)
    location = models.CharField(max_length=100, blank=True)
    references = models.ManyToManyField(Reference, related_name="boards", blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]

    def __str__(self):
        return self.name

    def get_absolute_url(self):
        return reverse("board-detail", args=[str(self.id)])

    def reference_count(self):
        return self.references.count()

    reference_count.short_description = "References"
